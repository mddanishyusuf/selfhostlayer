import { assertInt, assertSlug } from "@layer/protocol";
import { APP_ETC_ROOT, APPS_ROOT, sandboxLines } from "./app-unit.ts";

export interface RedisInput {
  slug: string;
  port: number;
  password: string;
  memoryMb: number;
  /** /usr/bin/redis-server, or valkey-server where the distro ships Valkey instead. */
  binary: string;
}

export const redisUnit = (slug: string) => `layer-redis-${assertSlug(slug)}.service`;

function assertPassword(value: string): string {
  if (!/^[0-9a-f]{32,128}$/.test(value)) throw new Error("redis password must be hex");
  return value;
}

/**
 * /etc/layer/apps/<slug>/redis.conf: this app's own Redis, on 127.0.0.1 only,
 * with a password, a memory cap, and its data in the app's data/ (so it's in
 * the app's backups).
 */
export function renderRedisConf(input: RedisInput): string {
  const slug = assertSlug(input.slug);
  const port = assertInt(input.port, "port", 1024, 65535);
  const memory = assertInt(input.memoryMb, "memoryMb", 16, 4096);
  return `# Generated by layer-agent: Redis for ${slug}. Change it in the panel.
bind 127.0.0.1
port ${port}
protected-mode yes
requirepass ${assertPassword(input.password)}
dir ${APPS_ROOT}/${slug}/data/redis
dbfilename dump.rdb
save 3600 1 300 100 60 10000
appendonly no
maxmemory ${memory}mb
# Errors instead of silently dropping keys: queues and sessions live here.
maxmemory-policy noeviction
daemonize no
supervised no
logfile ""
# Defaults on Redis 7+, written out so they hold everywhere: no runtime
# changes to dir/dbfilename, no DEBUG, no modules.
enable-protected-configs no
enable-debug-command no
enable-module-command no
`;
}

export function renderRedisUnit(input: RedisInput): string {
  const slug = assertSlug(input.slug);
  const memory = assertInt(input.memoryMb, "memoryMb", 16, 4096);
  if (!/^\/usr\/bin\/(redis|valkey)-server$/.test(input.binary)) throw new Error(`unexpected redis binary ${input.binary}`);
  const user = `app-${slug}`;
  return `# /etc/systemd/system/${redisUnit(slug)}
# Generated by layer-agent. Manage it in the panel.
[Unit]
Description=Redis for ${slug}
After=network.target

[Service]
Type=simple
User=${user}
Group=${user}
# systemd opens the config (root 600) and hands it over on stdin: the
# password never sits in a file the app's user can read.
StandardInput=file:${APP_ETC_ROOT}/${slug}/redis.conf
StandardOutput=journal
ExecStart=${input.binary} -
Restart=on-failure
RestartSec=2
SyslogIdentifier=${user}-redis
UMask=0077

${sandboxLines(memory + 64, 100, [`${APPS_ROOT}/${slug}/data/redis`])}
[Install]
WantedBy=multi-user.target
`;
}
