import { randomBytes } from "node:crypto";
import { assertSlug, ValidationError } from "@layer/protocol";
import { APPS_ROOT, sandboxLines } from "./app-unit.ts";

/** What the agent keeps about a WordPress site (root-only, beside its app.env). */
export interface WordpressState {
  version: string;
  url: string;
  salts: Record<string, string>;
  /** DISALLOW_FILE_MODS: no plugin, theme or core installs from wp-admin. */
  locked: boolean;
  xmlrpc: boolean;
  /** How wp_mail sends: Email's API, or SMTP, or not at all. */
  mail: WordpressMail | null;
}

export type WordpressMail =
  | { kind: "api"; url: string; key: string; from: string }
  | { kind: "smtp"; host: string; port: number; user: string; password: string; secure: "" | "tls" | "ssl"; from: string };

const SALT_KEYS = ["AUTH_KEY", "SECURE_AUTH_KEY", "LOGGED_IN_KEY", "NONCE_KEY", "AUTH_SALT", "SECURE_AUTH_SALT", "LOGGED_IN_SALT", "NONCE_SALT"];

/** Fresh salts: 64 characters each, from a set that needs no escaping in PHP. */
export function newSalts(): Record<string, string> {
  return Object.fromEntries(SALT_KEYS.map((k) => [k, randomBytes(48).toString("base64url")]));
}

export const assertWordpressVersion = (v: unknown): string => {
  if (typeof v !== "string" || !/^\d{1,2}\.\d{1,2}(\.\d{1,3})?$/.test(v)) throw new ValidationError("version", "must be a WordPress version like 7.1.4");
  return v;
};

/** An https:// or http:// origin, no path: the site's address. */
export const assertSiteUrl = (v: unknown, field = "url"): string => {
  if (typeof v !== "string" || !/^https?:\/\/[a-z0-9.-]{1,253}(:\d{1,5})?$/.test(v)) throw new ValidationError(field, "must be an address like https://blog.example.com");
  return v;
};

/** A PHP single-quoted string. */
const q = (s: string) => `'${s.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;

/** wp-config.php, generated: the panel's settings change it, and repair puts it back. */
export function renderWpConfig(state: WordpressState, db: { database: string; user: string; password: string }): string {
  const lines = [
    "<?php",
    "// Generated by Self Host Layer. Change these in the panel (Sites), not here:",
    "// this file is written again when settings change.",
    `define('DB_NAME', ${q(db.database)});`,
    `define('DB_USER', ${q(db.user)});`,
    `define('DB_PASSWORD', ${q(db.password)});`,
    "define('DB_HOST', '127.0.0.1:3306');",
    "define('DB_CHARSET', 'utf8mb4');",
    "define('DB_COLLATE', '');",
    ...SALT_KEYS.map((k) => `define('${k}', ${q(state.salts[k] ?? "")});`),
    "$table_prefix = 'wp_';",
    `define('WP_HOME', ${q(state.url)});`,
    `define('WP_SITEURL', ${q(state.url)});`,
    ...(state.url.startsWith("https://") ? ["define('FORCE_SSL_ADMIN', true);"] : []),
    "// WP-Cron runs from a timer every 5 minutes, not on visits.",
    "define('DISABLE_WP_CRON', true);",
    "define('DISALLOW_FILE_EDIT', true);",
    `define('DISALLOW_FILE_MODS', ${state.locked ? "true" : "false"});`,
    "define('FS_METHOD', 'direct');",
    "define('WP_AUTO_UPDATE_CORE', 'minor');",
    "define('WP_DEBUG', false);",
    ...mailLines(state.mail),
    "if (!defined('ABSPATH')) define('ABSPATH', __DIR__ . '/');",
    "require_once ABSPATH . 'wp-settings.php';",
    "",
  ];
  return lines.join("\n");
}

function mailLines(mail: WordpressMail | null): string[] {
  if (!mail) return [];
  if (mail.kind === "api") return [`define('LAYER_MAIL_API', ${q(mail.url)});`, `define('LAYER_MAIL_KEY', ${q(mail.key)});`, `define('LAYER_MAIL_FROM', ${q(mail.from)});`];
  return [
    `define('LAYER_SMTP_HOST', ${q(mail.host)});`,
    `define('LAYER_SMTP_PORT', ${mail.port});`,
    `define('LAYER_SMTP_USER', ${q(mail.user)});`,
    `define('LAYER_SMTP_PASSWORD', ${q(mail.password)});`,
    `define('LAYER_SMTP_SECURE', ${q(mail.secure)});`,
    `define('LAYER_SMTP_FROM', ${q(mail.from)});`,
  ];
}

/**
 * A must-use plugin: wp_mail through the Email integration's API (Resend's
 * shape) or SMTP, from the constants in wp-config.php. Without either, a
 * notice says WordPress can't send email.
 */
export const MAIL_PLUGIN = `<?php
/*
 * Plugin Name: Self Host Layer mail
 * Description: Sends WordPress's email through the server's Email integration or SMTP, as set in the panel (Sites).
 */
if (defined('LAYER_MAIL_API') && defined('LAYER_MAIL_KEY')) {
	add_filter('pre_wp_mail', function ($result, $atts) {
		$to = is_array($atts['to']) ? $atts['to'] : explode(',', $atts['to']);
		$headers = is_array($atts['headers']) ? implode("\\n", $atts['headers']) : (string) $atts['headers'];
		$html = stripos($headers, 'text/html') !== false;
		$body = array('from' => LAYER_MAIL_FROM, 'to' => array_values(array_filter(array_map('trim', $to))), 'subject' => $atts['subject']);
		$body[$html ? 'html' : 'text'] = $atts['message'];
		if (preg_match('/^Reply-To:\\s*(.+)$/mi', $headers, $m)) $body['reply_to'] = trim($m[1]);
		$response = wp_remote_post(rtrim(LAYER_MAIL_API, '/') . '/emails', array(
			'headers' => array('Authorization' => 'Bearer ' . LAYER_MAIL_KEY, 'Content-Type' => 'application/json'),
			'body' => wp_json_encode($body),
			'timeout' => 15,
		));
		$ok = !is_wp_error($response) && wp_remote_retrieve_response_code($response) < 300;
		if (!$ok) do_action('wp_mail_failed', new WP_Error('wp_mail_failed', is_wp_error($response) ? $response->get_error_message() : wp_remote_retrieve_body($response), $atts));
		return $ok;
	}, 10, 2);
} elseif (defined('LAYER_SMTP_HOST')) {
	add_action('phpmailer_init', function ($mailer) {
		$mailer->isSMTP();
		$mailer->Host = LAYER_SMTP_HOST;
		$mailer->Port = LAYER_SMTP_PORT;
		$mailer->SMTPAuth = LAYER_SMTP_USER !== '';
		$mailer->Username = LAYER_SMTP_USER;
		$mailer->Password = LAYER_SMTP_PASSWORD;
		$mailer->SMTPSecure = LAYER_SMTP_SECURE;
		$mailer->setFrom(LAYER_SMTP_FROM, get_bloginfo('name'), false);
	});
} else {
	add_action('admin_notices', function () {
		if (current_user_can('manage_options')) echo '<div class="notice notice-warning"><p>This site can\\'t send email yet: set up email for it in your Self Host Layer panel (Sites).</p></div>';
	});
}
`;

export const wpCronUnitName = (slug: string) => `app-${assertSlug(slug)}-wpcron`;

/** WP-Cron, every 5 minutes as the site's user with the site's lockdown. */
export function renderWpCronUnits(slug: string, phar: string): { service: string; timer: string } {
  assertSlug(slug);
  const name = wpCronUnitName(slug);
  const docroot = `${APPS_ROOT}/${slug}/data/wordpress`;
  return {
    service: `# /etc/systemd/system/${name}.service
# Generated by layer-agent. Run \`layer repair\` instead of editing.
[Unit]
Description=layer site ${slug}: WP-Cron

[Service]
Type=oneshot
User=app-${slug}
Group=app-${slug}
WorkingDirectory=${docroot}
Environment=HOME=/tmp WP_CLI_CACHE_DIR=/tmp/wp-cli
ExecStart=/usr/bin/php -d memory_limit=256M ${phar} cron event run --due-now --quiet --path=${docroot}
SyslogIdentifier=app-${slug}-wpcron
UMask=0027
TimeoutStartSec=600

${sandboxLines(256, 50, [`${APPS_ROOT}/${slug}/data`])}`,
    timer: `# /etc/systemd/system/${name}.timer
# Generated by layer-agent. Run \`layer repair\` instead of editing.
[Unit]
Description=layer site ${slug}: WP-Cron every 5 minutes

[Timer]
OnCalendar=*:0/5
RandomizedDelaySec=30
Persistent=false

[Install]
WantedBy=timers.target
`,
  };
}

/** What Caddy never serves for a WordPress site. */
export function wordpressBlocks(xmlrpc: boolean): string[] {
  return ["/wp-config.php", "/wp-config-sample.php", "/readme.html", "/license.txt", "/wp-content/uploads/*.php", "/wp-content/debug.log", ...(xmlrpc ? [] : ["/xmlrpc.php"])];
}
