import { assertInt, assertRelativePath, assertSlug, ValidationError } from "@layer/protocol";
import { APPS_ROOT, APP_ETC_ROOT, sandboxLines } from "./app-unit.ts";
import { assertDomains, assertRedirects, type Redirect } from "./caddy-site.ts";

/** What a PHP site is given: its folder inside data/, and its limits. */
export interface PhpSettings {
  /** The docroot, relative to data/ (wordpress). */
  root: string;
  /** Files in the docroot Caddy must never read (wp-config.php). */
  private: string[];
  /** The whole site: the FPM master and its workers. */
  memoryMaxMb: number;
  /** PHP's own memory_limit per request. */
  phpMemoryMb: number;
  uploadMb: number;
  workers: number;
}

export const PHP_DEFAULTS = { memoryMaxMb: 512, phpMemoryMb: 256, uploadMb: 64, workers: 5 };

export function assertPhpSettings(params: Record<string, unknown>): PhpSettings {
  const root = assertRelativePath(params.root, "root");
  const priv = params.private ?? [];
  if (!Array.isArray(priv) || priv.length > 20) throw new ValidationError("private", "must be a list of at most 20 paths");
  return {
    root,
    private: priv.map((p, i) => assertRelativePath(p, `private[${i}]`)),
    memoryMaxMb: assertInt(params.memoryMaxMb ?? PHP_DEFAULTS.memoryMaxMb, "memoryMaxMb", 128, 16384),
    phpMemoryMb: assertInt(params.phpMemoryMb ?? PHP_DEFAULTS.phpMemoryMb, "phpMemoryMb", 32, 4096),
    uploadMb: assertInt(params.uploadMb ?? PHP_DEFAULTS.uploadMb, "uploadMb", 1, 2048),
    workers: assertInt(params.workers ?? PHP_DEFAULTS.workers, "workers", 1, 50),
  };
}

export const phpUnitName = (slug: string) => `app-${assertSlug(slug)}-php.service`;
export const phpSocketDir = (runRoot: string, slug: string) => `${runRoot}/${assertSlug(slug)}`;

/**
 * The site's own PHP-FPM: one master per site, as the site's user, with
 * workers only while requests come (ondemand), so an idle site costs one
 * process. open_basedir keeps PHP inside the site and its private /tmp.
 */
export function renderPhpFpmConf(slug: string, s: PhpSettings, runRoot: string): string {
  assertSlug(slug);
  const docroot = `${APPS_ROOT}/${slug}/data/${s.root}`;
  return `; Generated by layer-agent. Run \`layer repair\` instead of editing.
[global]
; To the journal, as app-${slug}-php (stderr is a socket FPM can't reopen).
error_log = syslog
syslog.ident = app-${slug}-php
log_level = notice
daemonize = no
systemd_interval = 10

[site]
listen = ${phpSocketDir(runRoot, slug)}/php.sock
; Only Caddy can get to it: the socket's folder is 0710 app-${slug}:caddy.
listen.mode = 0666
pm = ondemand
pm.max_children = ${s.workers}
pm.process_idle_timeout = 30s
pm.max_requests = 500
catch_workers_output = yes
decorate_workers_output = no
clear_env = yes
security.limit_extensions = .php
php_admin_value[open_basedir] = ${docroot}/:/tmp/
php_admin_value[upload_tmp_dir] = /tmp
php_admin_value[sys_temp_dir] = /tmp
php_admin_value[session.save_path] = /tmp
php_admin_value[memory_limit] = ${s.phpMemoryMb}M
php_admin_value[upload_max_filesize] = ${s.uploadMb}M
php_admin_value[post_max_size] = ${s.uploadMb}M
php_admin_value[max_execution_time] = 120
php_admin_value[disable_functions] = exec,passthru,shell_exec,system,proc_open,popen,pcntl_exec
php_admin_flag[expose_php] = off
php_admin_flag[display_errors] = off
php_admin_flag[log_errors] = on
php_admin_flag[allow_url_include] = off
`;
}

/** The FPM master as a sandboxed unit, like an app's: its own user, limits and lockdown. */
export function renderPhpUnit(slug: string, s: PhpSettings, fpm: string, runRoot: string, caddyGroup: string): string {
  assertSlug(slug);
  if (!/^\/usr\/sbin\/php-fpm[0-9.]+$/.test(fpm)) throw new ValidationError("fpm", "must be /usr/sbin/php-fpm<version>");
  const user = `app-${slug}`;
  const sock = phpSocketDir(runRoot, slug);
  return `# /etc/systemd/system/${phpUnitName(slug)}
# Generated by layer-agent. Run \`layer repair\` instead of editing.
[Unit]
Description=layer site ${slug} (PHP)
After=network-online.target
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=notify
User=${user}
Group=${user}
# The socket's folder: only the site and Caddy get in (privileged, before the sandbox).
ExecStartPre=+/usr/bin/install -d -m 0711 ${runRoot}
ExecStartPre=+/usr/bin/install -d -o ${user} -g ${caddyGroup} -m 0710 ${sock}
# The config is root's (the site can't loosen open_basedir); systemd hands the
# service a private, read-only copy in its credentials folder (%d).
LoadCredential=php-fpm.conf:${APP_ETC_ROOT}/${slug}/php-fpm.conf
ExecStart=${fpm} --nodaemonize --fpm-config %d/php-fpm.conf -d opcache.memory_consumption=48 -d opcache.jit=off
ExecReload=/bin/kill -USR2 $MAINPID
Restart=on-failure
RestartSec=2
SyslogIdentifier=${user}-php
UMask=0027

${sandboxLines(s.memoryMaxMb, 100, [`${APPS_ROOT}/${slug}/data`, `-${sock}`])}
[Install]
WantedBy=multi-user.target
`;
}

/** URL paths no PHP site serves: dotfiles (but /.well-known), plus the site's own list. */
const PATTERN = /^\/[A-Za-z0-9._*/-]{0,200}$/;
export function assertBlocks(value: unknown): string[] {
  if (value === undefined) return [];
  if (!Array.isArray(value) || value.length > 40) throw new ValidationError("block", "must be a list of at most 40 paths");
  return value.map((p, i) => {
    if (typeof p !== "string" || !PATTERN.test(p)) throw new ValidationError(`block[${i}]`, "must be a URL path like /wp-config.php or /uploads/*.php");
    return p;
  });
}

export interface PhpSiteInput {
  slug: string;
  domains: string[];
  redirects?: Redirect[];
  /** /srv/apps/<slug>/data/<root> */
  docroot: string;
  socket: string;
  block: string[];
  uploadMb: number;
}

/** A PHP site: Caddy serves the files, and hands .php to the site's FPM socket. */
export function renderPhpSite(input: PhpSiteInput): string {
  const slug = assertSlug(input.slug);
  const domains = assertDomains(input.domains);
  const redirects = assertRedirects(input.redirects, domains);
  const block = assertBlocks(input.block);
  const blocked = block.length ? `\t@blocked path ${block.join(" ")}\n\trespond @blocked 404\n` : "";
  return `# layer: slug=${slug} live=php
# Generated by layer-agent. Run \`layer repair\` instead of editing.
${domains.join(", ")} {
\tencode zstd gzip
\troot * ${input.docroot}
\trequest_body {
\t\tmax_size ${input.uploadMb + 1}MB
\t}
\t@dotfiles {
\t\tpath /.*
\t\tnot path /.well-known/*
\t}
\trespond @dotfiles 404
${blocked}\tphp_fastcgi unix/${input.socket}
\tfile_server
\tlog {
\t\toutput file /var/log/caddy/${slug}.log {
\t\t\troll_size 10MiB
\t\t\troll_keep 5
\t\t}
\t\tformat json
\t}
}
${redirects.map((r) => `\n${r.from} {\n\tredir https://${r.to}{uri} permanent\n}\n`).join("")}`;
}
