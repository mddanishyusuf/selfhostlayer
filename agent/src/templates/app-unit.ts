import {
  ValidationError,
  assertInt,
  assertLine,
  assertNodeVersion,
  assertRelativePath,
  assertSlug,
} from "@layer/protocol";

export interface AppUnitInput {
  slug: string;
  nodeVersion: string;
  /** argv for the app process. argv[0] must be one of NODE_BINS; it resolves to the pinned runtime. */
  exec: string[];
  memoryMaxMb: number;
  cpuQuotaPercent: number;
  /** Paths inside the app's folder it writes to at runtime, e.g. ".next/cache". */
  writablePaths?: string[];
  /** The app's folder inside the repo, for monorepos (e.g. "apps/web"). */
  rootDir?: string;
}

const NODE_BINS = ["node", "npm", "npx"] as const;
const SAFE_ARG = /^[A-Za-z0-9_@+=:,./-]+$/;

export const APPS_ROOT = "/srv/apps";
export const NODE_ROOT = "/opt/layer/node";
export const APP_ETC_ROOT = "/etc/layer/apps";

export function unitName(slug: string): string {
  return `app-${assertSlug(slug)}@.service`;
}

/**
 * Renders /etc/systemd/system/app-<slug>@.service. Instances are the deploy
 * colors (blue/green): %i picks the release symlink and the PORT env file.
 */
export function renderAppUnit(input: AppUnitInput): string {
  const slug = assertSlug(input.slug);
  const nodeVersion = assertNodeVersion(input.nodeVersion);
  const memoryMax = assertInt(input.memoryMaxMb, "memoryMaxMb", 64, 16384);
  const cpuQuota = assertInt(input.cpuQuotaPercent, "cpuQuotaPercent", 10, 800);
  const writable = (input.writablePaths ?? []).map((p) => assertRelativePath(p, "writablePaths"));
  const rootDir = input.rootDir ? assertRelativePath(input.rootDir, "rootDir") : null;
  const execStart = renderExecStart(input.exec, nodeVersion);

  const user = `app-${slug}`;
  const appDir = `${APPS_ROOT}/${slug}`;
  const nodeBin = `${NODE_ROOT}/${nodeVersion}/bin`;
  const workDir = rootDir ? `${appDir}/%i/${rootDir}` : `${appDir}/%i`;
  // "-" prefix: don't fail the start if the release hasn't created the dir.
  const readWritePaths = [`${appDir}/data`, ...writable.map((p) => `-${workDir}/${p}`)];

  return `# /etc/systemd/system/${unitName(slug)}
# Generated by layer-agent. Run \`layer repair\` instead of editing.
[Unit]
Description=layer app ${slug} (%i)
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=simple
User=${user}
Group=${user}
WorkingDirectory=${workDir}
Environment=DATA_DIR=${appDir}/data
# Credentials for the app's Redis/Postgres (made by the agent), then the
# user's env vars (which win), then the color's PORT.
EnvironmentFile=-${APP_ETC_ROOT}/${slug}/services.env
EnvironmentFile=${APP_ETC_ROOT}/${slug}/app.env
EnvironmentFile=${APP_ETC_ROOT}/${slug}/%i.env
Environment=PATH=${nodeBin}:/usr/bin:/bin
ExecStart=${execStart}
Restart=on-failure
RestartSec=2
# Next.js and others exit 143 (128 + SIGTERM) when stopped; that's a clean stop.
SuccessExitStatus=143
SyslogIdentifier=${user}-%i
UMask=0077

${sandboxLines(memoryMax, cpuQuota, readWritePaths)}
[Install]
WantedBy=multi-user.target
`;
}

/**
 * Resource limits and the sandbox, shared by app units and cron services:
 * a cron job gets exactly the same lockdown as the app it belongs to.
 */
export function sandboxLines(memoryMaxMb: number, cpuQuotaPercent: number, readWritePaths: string[]): string {
  return `# Resources
MemoryHigh=${Math.floor(memoryMaxMb * 0.8)}M
MemoryMax=${memoryMaxMb}M
CPUQuota=${cpuQuotaPercent}%
TasksMax=256
LimitNOFILE=65536

# Sandbox
NoNewPrivileges=yes
CapabilityBoundingSet=
AmbientCapabilities=
ProtectSystem=strict
ProtectHome=yes
ReadWritePaths=${readWritePaths.join(" ")}
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
ProtectProc=invisible
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX AF_NETLINK
PrivateIPC=yes
# Nothing an app needs, and a way in for one that's compromised: the system
# D-Bus, and the cloud's metadata service (169.254.169.254 at Hetzner, AWS…).
InaccessiblePaths=-/run/dbus
IPAddressDeny=169.254.0.0/16
SystemCallFilter=@system-service
SystemCallFilter=~@privileged @resources
SystemCallErrorNumber=EPERM
SystemCallArchitectures=native
`;
}

export function renderExecStart(exec: string[], nodeVersion: string): string {
  if (!Array.isArray(exec) || exec.length === 0 || exec.length > 64) {
    throw new ValidationError("exec", "must be a non-empty argv array");
  }
  const [bin, ...args] = exec;
  if (!NODE_BINS.includes(bin as (typeof NODE_BINS)[number])) {
    throw new ValidationError("exec", `argv[0] must be one of ${NODE_BINS.join(", ")}`);
  }
  const argv = [`${NODE_ROOT}/${nodeVersion}/bin/${bin}`, ...args.map((a, i) => quoteArg(a, i + 1))];
  return argv.join(" ");
}

/**
 * Quotes one argument for an ExecStart= line. systemd expands % specifiers and
 * $VARIABLES inside ExecStart, so both are escaped; anything outside the safe
 * set is double-quoted with C-style escapes.
 */
function quoteArg(arg: unknown, index: number): string {
  const value = assertLine(arg, `exec[${index}]`, 1024);
  if (value === "" || value === ";") {
    throw new ValidationError(`exec[${index}]`, "must not be empty or a bare ';'");
  }
  const escaped = value.replaceAll("%", "%%").replaceAll("$", "$$$$");
  if (SAFE_ARG.test(value)) return escaped;
  return `"${escaped.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}
