import { assertInt, assertNodeVersion, assertRelativePath, assertSlug, ValidationError } from "@layer/protocol";
import { APP_ETC_ROOT, APPS_ROOT, NODE_ROOT, renderExecStart, sandboxLines } from "./app-unit.ts";

const CRON_NAME = /^[a-z][a-z0-9-]{0,30}$/;
// systemd OnCalendar syntax only (the agent also runs `systemd-analyze calendar` on it).
const CALENDAR = /^[A-Za-z0-9*:,./ -]{1,100}$/;

export function assertCronName(value: unknown): string {
  if (typeof value !== "string" || !CRON_NAME.test(value)) throw new ValidationError("name", "must be 1-31 chars of a-z, 0-9 and -, starting with a letter");
  return value;
}

export function assertCalendar(value: unknown): string {
  if (typeof value !== "string" || !CALENDAR.test(value)) throw new ValidationError("calendar", "must be a systemd OnCalendar expression");
  return value;
}

export const cronUnit = (slug: string, name: string) => `app-${slug}-cron-${name}`;

export interface CronUnitInput {
  slug: string;
  name: string;
  calendar: string;
  nodeVersion: string;
  exec: string[];
  rootDir?: string;
  memoryMaxMb: number;
  timeoutSec: number;
  writablePaths?: string[];
}

/**
 * One run of a cron job: the app's user, env, Node and sandbox, from the live
 * release (/srv/apps/<slug>/current). Type=oneshot, killed after timeoutSec.
 */
export function renderCronService(input: CronUnitInput): string {
  const slug = assertSlug(input.slug);
  const name = assertCronName(input.name);
  const nodeVersion = assertNodeVersion(input.nodeVersion);
  const memory = assertInt(input.memoryMaxMb, "memoryMaxMb", 64, 16384);
  const timeout = assertInt(input.timeoutSec, "timeoutSec", 10, 86_400);
  const rootDir = input.rootDir ? assertRelativePath(input.rootDir, "rootDir") : null;
  const writable = (input.writablePaths ?? []).map((p) => assertRelativePath(p, "writablePaths"));
  const appDir = `${APPS_ROOT}/${slug}`;
  const workDir = rootDir ? `${appDir}/current/${rootDir}` : `${appDir}/current`;
  const user = `app-${slug}`;
  return `# /etc/systemd/system/${cronUnit(slug, name)}.service
# Generated by layer-agent. Manage crons in the panel.
[Unit]
Description=layer cron ${slug}/${name}

[Service]
Type=oneshot
User=${user}
Group=${user}
WorkingDirectory=${workDir}
EnvironmentFile=${APP_ETC_ROOT}/${slug}/app.env
Environment=PATH=${NODE_ROOT}/${nodeVersion}/bin:/usr/bin:/bin
Environment=NODE_ENV=production
ExecStart=${renderExecStart(input.exec, nodeVersion)}
TimeoutStartSec=${timeout}
SyslogIdentifier=${user}-cron-${name}
UMask=0077

${sandboxLines(memory, 100, [`${appDir}/data`, ...writable.map((p) => `-${workDir}/${p}`)])}`;
}

export function renderCronTimer(input: Pick<CronUnitInput, "slug" | "name" | "calendar">): string {
  const slug = assertSlug(input.slug);
  const name = assertCronName(input.name);
  const calendar = assertCalendar(input.calendar);
  return `# /etc/systemd/system/${cronUnit(slug, name)}.timer
# Generated by layer-agent. Manage crons in the panel.
[Unit]
Description=layer cron ${slug}/${name} schedule

[Timer]
OnCalendar=${calendar}
AccuracySec=1s
# Run once after boot if a scheduled run was missed while the server was down.
Persistent=true
Unit=${cronUnit(slug, name)}.service

[Install]
WantedBy=timers.target
`;
}
