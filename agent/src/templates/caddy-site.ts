import { assertColor, assertDomain, assertInt, assertSlug, ValidationError, type Color } from "@layer/protocol";

export interface CaddySiteInput {
  slug: string;
  color: Color;
  port: number;
  domains: string[];
}

const MAX_DOMAINS = 20;

export function assertDomains(value: unknown): string[] {
  if (!Array.isArray(value) || value.length === 0 || value.length > MAX_DOMAINS) {
    throw new ValidationError("domains", `must be a list of 1-${MAX_DOMAINS} hostnames`);
  }
  const domains = value.map((d, i) => assertDomain(d, `domains[${i}]`));
  if (new Set(domains).size !== domains.length) throw new ValidationError("domains", "contains duplicates");
  return domains;
}

/**
 * Renders /etc/caddy/sites/<slug>.caddy. The first line records which color
 * is live, so `layer status` and the panel can read it back from the file.
 */
export function renderCaddySite(input: CaddySiteInput): string {
  const slug = assertSlug(input.slug);
  const color = assertColor(input.color);
  const port = assertInt(input.port, "port", 1024, 65535);
  const domains = assertDomains(input.domains);

  return `# layer: slug=${slug} live=${color} port=${port}
# Generated by layer-agent. Run \`layer repair\` instead of editing.
${domains.join(", ")} {
	encode zstd gzip
	reverse_proxy 127.0.0.1:${port} {
		# Retry briefly instead of failing while an upstream restarts.
		lb_try_duration 5s
	}
	log {
		output file /var/log/caddy/${slug}.log {
			roll_size 10MiB
			roll_keep 5
		}
		format json
	}
}
`;
}

export interface LiveMarker {
  slug: string;
  color: Color | "static";
  port: number | null;
}

export function parseLiveMarker(content: string): LiveMarker | null {
  const match = /^# layer: slug=([a-z0-9-]+) live=(blue|green|static)(?: port=(\d+))?$/m.exec(content);
  if (!match) return null;
  return match[2] === "static"
    ? { slug: match[1]!, color: "static", port: null }
    : { slug: match[1]!, color: match[2] as Color, port: Number(match[3]) };
}

export interface StaticSiteInput {
  slug: string;
  domains: string[];
  /** Single-page app: unknown paths serve /index.html instead of a 404. */
  spa: boolean;
  /** /srv/static/<slug>/current */
  root: string;
}

/**
 * A static site: Caddy serves the published files directly, no Node process.
 * Hashed asset folders (Vite's /assets, Astro's /_astro) are cached forever.
 */
export function renderStaticSite(input: StaticSiteInput): string {
  const slug = assertSlug(input.slug);
  const domains = assertDomains(input.domains);
  const fallback = input.spa
    ? "\ttry_files {path} {path}/ /index.html\n"
    : "\ttry_files {path} {path}.html {path}/\n";
  const notFound = input.spa
    ? ""
    : `\thandle_errors 404 {
\t\trewrite * /404.html
\t\tfile_server
\t}
`;
  return `# layer: slug=${slug} live=static
# Generated by layer-agent. Run \`layer repair\` instead of editing.
${domains.join(", ")} {
\tencode zstd gzip
\troot * ${input.root}
\theader /assets/* Cache-Control "public, max-age=31536000, immutable"
\theader /_astro/* Cache-Control "public, max-age=31536000, immutable"
${fallback}\tfile_server
${notFound}\tlog {
\t\toutput file /var/log/caddy/${slug}.log {
\t\t\troll_size 10MiB
\t\t\troll_keep 5
\t\t}
\t\tformat json
\t}
}
`;
}
