// MySQL 8 for Ghost (Sites): Oracle's own build, from a signed tarball, run
// beside MariaDB on its own port. See PLAN-SITES.md.

export const MYSQL8 = {
  version: "8.4.13",
  base: "https://cdn.mysql.com/Downloads/MySQL-8.4",
  /** x86_64 has a stripped build; aarch64 only the full one (its debug binaries aren't unpacked). */
  tarball: (version: string, arch: "x64" | "arm64") => `mysql-${version}-linux-glibc2.28-${arch === "x64" ? "x86_64-minimal" : "aarch64"}.tar.xz`,
  root: "/opt/layer/mysql",
  datadir: "/var/lib/layer-mysql8",
  runDir: "/run/layer-mysql8",
  conf: "/etc/layer/mysql8.cnf",
  user: "mysql8",
  port: 3307,
  unit: "layer-mysql8.service",
};

export const mysql8Bin = (version: string, bin: "mysqld" | "mysql" | "mysqldump" | "mysqladmin") => `${MYSQL8.root}/${version}/bin/${bin}`;
/** Where libaio.so.1 points at the distro's libaio.so.1t64 (Ubuntu 24.04 and later renamed it). */
export const mysql8Compat = (version: string) => `${MYSQL8.root}/${version}/lib/compat`;

/** The server's config. setup: the first start, socket only, while root gets its password. */
export function renderMysql8Conf(version: string, setup: boolean, totalMb: number): string {
  // Small boxes get a small pool: Ghost's tables are small.
  const pool = totalMb >= 8192 ? 512 : totalMb >= 4096 ? 256 : 128;
  return `# Generated by layer-agent. Run \`layer repair\` instead of editing.
[mysqld]
user=${MYSQL8.user}
basedir=${MYSQL8.root}/${version}
datadir=${MYSQL8.datadir}
socket=${MYSQL8.runDir}/mysqld.sock
pid-file=${MYSQL8.runDir}/mysqld.pid
port=${MYSQL8.port}
bind-address=127.0.0.1
${setup ? "skip-networking\n" : ""}mysqlx=OFF
performance_schema=OFF
skip-name-resolve
innodb_buffer_pool_size=${pool}M
innodb_log_buffer_size=8M
max_connections=60
table_open_cache=400
character-set-server=utf8mb4
collation-server=utf8mb4_0900_ai_ci

[client]
socket=${MYSQL8.runDir}/mysqld.sock
`;
}

export function renderMysql8Unit(version: string): string {
  return `# /etc/systemd/system/${MYSQL8.unit}
# Generated by layer-agent. Run \`layer repair\` instead of editing.
[Unit]
Description=layer MySQL 8 (for Ghost sites)
After=network-online.target

[Service]
Type=exec
User=${MYSQL8.user}
Group=${MYSQL8.user}
RuntimeDirectory=layer-mysql8
RuntimeDirectoryMode=0750
Environment=LD_LIBRARY_PATH=${mysql8Compat(version)}
ExecStart=${mysql8Bin(version, "mysqld")} --defaults-file=${MYSQL8.conf} --console
Restart=on-failure
RestartSec=5
StartLimitIntervalSec=120
StartLimitBurst=5
TimeoutStopSec=300
LimitNOFILE=10000
SyslogIdentifier=layer-mysql8

NoNewPrivileges=yes
CapabilityBoundingSet=
ProtectSystem=strict
ReadWritePaths=${MYSQL8.datadir}
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectControlGroups=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
RestrictSUIDSGID=yes
LockPersonality=yes

[Install]
WantedBy=multi-user.target
`;
}
