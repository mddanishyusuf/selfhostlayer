import { assertInt, assertNodeVersion, assertRelativePath, assertSlug, ValidationError } from "@layer/protocol";
import { APP_ETC_ROOT, APPS_ROOT, NODE_ROOT, renderExecStart, sandboxLines } from "./app-unit.ts";

const WORKER_NAME = /^[a-z][a-z0-9-]{0,30}$/;

export function assertWorkerName(value: unknown): string {
  if (typeof value !== "string" || !WORKER_NAME.test(value)) throw new ValidationError("name", "must be 1-31 chars of a-z, 0-9 and -, starting with a letter");
  return value;
}

export const workerUnit = (slug: string, name: string) => `app-${slug}-worker-${name}.service`;

export interface WorkerUnitInput {
  slug: string;
  name: string;
  nodeVersion: string;
  exec: string[];
  rootDir?: string;
  memoryMaxMb: number;
  writablePaths?: string[];
}

/**
 * A worker: a second long-running process of the app (a queue consumer, a
 * bot), with the app's user, env, Node and sandbox, from the live release
 * (/srv/apps/<slug>/current). It restarts when it exits; deploys restart it
 * so it runs the code that's live.
 */
export function renderWorkerUnit(input: WorkerUnitInput): string {
  const slug = assertSlug(input.slug);
  const name = assertWorkerName(input.name);
  const nodeVersion = assertNodeVersion(input.nodeVersion);
  const memory = assertInt(input.memoryMaxMb, "memoryMaxMb", 64, 16384);
  const rootDir = input.rootDir ? assertRelativePath(input.rootDir, "rootDir") : null;
  const writable = (input.writablePaths ?? []).map((p) => assertRelativePath(p, "writablePaths"));
  const appDir = `${APPS_ROOT}/${slug}`;
  const workDir = rootDir ? `${appDir}/current/${rootDir}` : `${appDir}/current`;
  const user = `app-${slug}`;
  return `# /etc/systemd/system/${workerUnit(slug, name)}
# Generated by layer-agent. Manage workers on the project's Processes page.
[Unit]
Description=layer worker ${slug}/${name}
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=simple
User=${user}
Group=${user}
WorkingDirectory=${workDir}
Environment=DATA_DIR=${appDir}/data
EnvironmentFile=-${APP_ETC_ROOT}/${slug}/services.env
EnvironmentFile=${APP_ETC_ROOT}/${slug}/app.env
Environment=PATH=${NODE_ROOT}/${nodeVersion}/bin:/usr/bin:/bin
Environment=NODE_ENV=production
# For \`npm run …\`: the app's home folder is read-only.
Environment=npm_config_cache=/tmp/.npm npm_config_update_notifier=false
ExecStart=${renderExecStart(input.exec, nodeVersion)}
Restart=always
RestartSec=2
TimeoutStopSec=30
SuccessExitStatus=143
SyslogIdentifier=${user}-worker-${name}
UMask=0077

${sandboxLines(memory, 100, [`${appDir}/data`, ...writable.map((p) => `-${workDir}/${p}`)])}
[Install]
WantedBy=multi-user.target
`;
}
