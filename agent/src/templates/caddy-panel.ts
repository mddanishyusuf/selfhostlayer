import { isIP } from "node:net";
import { assertDomain, ValidationError } from "@layer/protocol";

export interface PanelSiteInput {
  /** Where the panel answers. The first is its address; others are being moved to. */
  hosts: string[];
  /** Old addresses that redirect to the first host, keeping the path. */
  redirects: string[];
  /** Caddy's local CA instead of Let's Encrypt (test boxes). */
  internalTls: boolean;
  /** Addresses (IPs or CIDR ranges) the panel answers; empty: anyone. */
  allow?: string[];
}

/** Caddy reaches the panel only through this socket (layer-web group). */
export const PANEL_SOCKET = "/run/layer-panel/panel.sock";

/** IPs and CIDR ranges (1.2.3.4, 10.0.0.0/8, fd7a:115c:a1e0::/48), at most 50. */
export function assertRanges(value: unknown, field = "allow"): string[] {
  if (!Array.isArray(value) || value.length > 50) throw new ValidationError(field, "must be a list of at most 50 addresses");
  const ranges = value.map((v, i) => {
    const [ip, bits, extra] = typeof v === "string" ? v.split("/") : [];
    const family = ip ? isIP(ip) : 0;
    const max = family === 4 ? 32 : 128;
    const ok = family !== 0 && extra === undefined && (bits === undefined || (/^\d{1,3}$/.test(bits) && Number(bits) <= max));
    if (!ok) throw new ValidationError(`${field}[${i}]`, "must be an IP address or a range like 203.0.113.0/24");
    return v as string;
  });
  if (new Set(ranges).size !== ranges.length) throw new ValidationError(field, "contains duplicates");
  return ranges;
}

/** A list of hostnames: valid, no duplicates, between min and max long. */
export function assertHosts(value: unknown, field: string, min: number, max = 10): string[] {
  if (!Array.isArray(value) || value.length < min || value.length > max) throw new ValidationError(field, `must be a list of ${min}-${max} hostnames`);
  const hosts = value.map((h, i) => assertDomain(h, `${field}[${i}]`));
  if (new Set(hosts).size !== hosts.length) throw new ValidationError(field, "contains duplicates");
  return hosts;
}

/**
 * Renders /etc/caddy/sites/_panel.caddy (_panel can't clash with an app:
 * app slugs start with a letter).
 */
export function renderPanelSite(input: PanelSiteInput): string {
  const hosts = assertHosts(input.hosts, "hosts", 1);
  const redirects = assertHosts(input.redirects, "redirects", 0);
  if (redirects.some((r) => hosts.includes(r))) throw new ValidationError("redirects", "a host can't both serve the panel and redirect to it");
  const tls = input.internalTls ? "\n\ttls internal" : "";
  const allow = assertRanges(input.allow ?? []);
  // GitHub's webhook stays reachable: deliveries are signed, and blocking them would stop deploys on push.
  const guard = allow.length
    ? `
	@outside {
		not remote_ip ${allow.join(" ")}
		not path /api/github/webhook
	}
	respond @outside "This panel only answers from allowed addresses." 403`
    : "";
  return `# Self Host Layer panel. Generated by layer-agent: change the address in Settings → Panel address.
${hosts.join(", ")} {${tls}${guard}
	encode zstd gzip
	reverse_proxy unix/${PANEL_SOCKET}
	log {
		output file /var/log/caddy/_panel.log {
			roll_size 10MiB
			roll_keep 5
		}
		format json
	}
}
${redirects.map((r) => `\n${r} {${tls}\n\tredir https://${hosts[0]}{uri} permanent\n}\n`).join("")}`;
}
